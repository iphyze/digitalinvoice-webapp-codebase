import api from './api';

const platformService = {
  dashboard: () => api.get('/platform/dashboard'),
  clients: (params = {}) => api.get('/platform/clients', { params }),
  client: (id) => api.get('/platform/client', { params: { id } }),
  updateClientAccount: (payload) => api.put('/platform/client', payload),
  plans: (params = {}) => api.get('/platform/plans', { params }),
  createPlan: (payload) => api.post('/platform/plans', payload),
  updatePlan: (payload) => api.put('/platform/plans', payload),
  subscriptions: (params = {}) => api.get('/platform/subscriptions', { params }),
  premiumRequests: (params = {}) => api.get('/platform/premium-requests', { params }),
  updatePremiumRequest: (payload) => api.put('/platform/premium-requests', payload),
  subscriptionLifecycle: () => api.get('/platform/subscriptions/lifecycle'),
  syncSubscriptionLifecycle: () => api.post('/platform/subscriptions/lifecycle', { action: 'sync_expired' }),
  sendSubscriptionNotifications: () => api.post('/platform/subscriptions/lifecycle', { action: 'send_notifications' }),
  syncAndNotifySubscriptionLifecycle: () => api.post('/platform/subscriptions/lifecycle', { action: 'sync_and_notify' }),
  revenue: (params = {}) => api.get('/platform/revenue', { params }),
  activity: (params = {}) => api.get('/platform/activity', { params }),
  settings: () => api.get('/platform/settings'),
  updateSettings: (payload) => api.put('/platform/settings', payload),
  firsIntegration: () => api.get('/platform/firs-integration'),
  nrsSandboxHealth: () => api.post('/platform/firs-sandbox-health', {}),
  updateFirsIntegration: (payload) => api.put('/platform/firs-integration', payload),
  updateFirsResource: (payload) => api.put('/platform/firs-resources', payload),
  profile: () => api.get('/platform/profile'),
  updateProfile: (payload) => api.put('/platform/profile', payload),
  subscription: (id) => api.get('/platform/subscription', { params: { id } }),
  manageSubscription: (payload) => api.put('/platform/subscription', payload),
  users: () => api.get('/platform/users'),
  inviteUser: (payload) => api.post('/platform/users', payload),
  resendInvitation: (payload) => api.put('/platform/users', { action: 'resend_invitation', ...payload }),
  validateInvitation: (token) => api.get('/platform/invitations/validate', { params: { token }, skipAuthRefresh: true, skipCsrf: true }),
  acceptInvitation: (payload) => api.post('/platform/invitations/accept', payload, { skipAuthRefresh: true, skipCsrf: true }),
  updateUser: (payload) => api.put('/platform/users', payload),
  removeUser: (payload) => api.delete('/platform/users', { data: payload }),
};

export default platformService;
